// Builds the generated parts of the skill: the engine for scripts/build.mjs (scripts/engine.mjs: find, extract, compare,
// review, the workbook and its way back — with the YAML reader inside, so the skill runs on Node alone) and the map page
// with its code inside (assets/map.html), the lesson page (visual-explainer's player), from src/ and the way engine's xlsx writer, pinned by tools/sources.json; the
// kit's browser and page helpers; the workbook reader, copied from way-of-working; and references/keys.md, from the
// names in src/labels.ts. Run: npm run assets. Never edit the generated files by hand.
import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { vendor } from '@ruinosus/visual-explainer/kit/tools/vendor.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const repo = resolve(here, '../../..') // the dna repository
const skill = join(repo, 'skills/agent-review')
const config = join(here, 'sources.json')
if (!existsSync(config)) {
  console.error('✗ tools/sources.json is missing: copy sources.example.json and point it at the way engine.')
  process.exit(1)
}
const lib = resolve(here, JSON.parse(readFileSync(config, 'utf8')).lib)
// the pieces used must be committed, so VERSION says exactly what the skill was built from
const used = ['ways/xlsx.ts', 'ways/workbook.ts', 'drawing']
if (execFileSync('git', ['-C', lib, 'status', '--porcelain', '--', ...used], { encoding: 'utf8' }).trim()) throw new Error(`${lib} has uncommitted changes in ${used.join(', ')}: commit them first.`)
const version = execFileSync('git', ['-C', lib, 'describe', '--tags', '--always'], { encoding: 'utf8' }).trim()
const chalk = JSON.parse(readFileSync(join(repo, 'node_modules/@ruinosus/visual-explainer/package.json'), 'utf8')).version
// the plugin's version, written into what each run makes, so two runs can be told apart
const release = JSON.parse(readFileSync(join(repo, '.claude-plugin/plugin.json'), 'utf8')).version
const banner = `// GENERATED by tools/assets.mjs (way engine ${version}). Do not edit.`
// tools/.lib points at the engine, for the typecheck and the checks (tsconfig paths)
rmSync(join(here, '.lib'), { force: true })
symlinkSync(lib, join(here, '.lib'))
// the engine's own files have no side effects: what is not used is left out
const pure = {
  name: 'pure',
  setup(b) {
    b.onResolve({ filter: /^\.\.?\// }, async (a) => {
      if (a.pluginData === 'resolving') return undefined
      const r = await b.resolve(a.path, { resolveDir: a.resolveDir, kind: a.kind, pluginData: 'resolving' })
      return r.errors.length || r.path.includes('node_modules') || !r.path.startsWith(lib) ? r : { ...r, sideEffects: false }
    })
  },
}
const common = { bundle: true, minify: true, write: false, logLevel: 'warning', define: { __RELEASE__: JSON.stringify(release) }, alias: { '@lib': lib, '@kit': join(repo, 'node_modules/@ruinosus/visual-explainer/kit') }, nodePaths: [join(repo, 'node_modules'), join(lib, 'node_modules')], plugins: [pure] }
const engine = await build({ ...common, entryPoints: [join(root, 'src/engine.ts')], format: 'esm', platform: 'node', target: 'node18', banner: { js: "import { createRequire } from 'node:module'; const require = createRequire(import.meta.url);" } })
mkdirSync(join(skill, 'scripts'), { recursive: true })
writeFileSync(join(skill, 'scripts/engine.mjs'), `${banner}\n${engine.outputFiles[0].text}`)
// the map page, with its code inside
const css = readFileSync(join(root, 'src/page/map.css'), 'utf8')
const page = await build({ ...common, entryPoints: [join(root, 'src/page/map.ts')], format: 'iife', target: 'es2020', define: { ...common.define, __MAP_CSS__: JSON.stringify(css) } })
const script = page.outputFiles[0].text
if (/<\/script/i.test(script)) throw new Error('The map script contains "</script": it would end the page early.')
const html = readFileSync(join(root, 'src/page/template.html'), 'utf8').replace(/\{\{(VERSION|CSS|JS)\}\}/g, (_, k) => ({ VERSION: `${release}, engine ${version}`, CSS: css, JS: script })[k])
if (!html.includes('{{CAST}}')) throw new Error('The template lost its {{CAST}} slot.')
mkdirSync(join(skill, 'assets'), { recursive: true })
writeFileSync(join(skill, 'assets/map.html'), html)
// the RH page, with its code inside, on the same template
const pbCss = readFileSync(join(root, 'src/page/playbill.css'), 'utf8')
const pbScript = (await build({ ...common, entryPoints: [join(root, 'src/page/playbill.ts')], format: 'iife', target: 'es2020' })).outputFiles[0].text
if (/<\/script/i.test(pbScript)) throw new Error('The RH script contains "</script": it would end the page early.')
const pbHtml = readFileSync(join(root, 'src/page/template.html'), 'utf8').replace(/\{\{(VERSION|CSS|JS)\}\}/g, (_, k) => ({ VERSION: `${release}, engine ${version}`, CSS: pbCss, JS: pbScript })[k])
writeFileSync(join(skill, 'assets/playbill.html'), pbHtml)
// the stage page, likewise
const plCss = readFileSync(join(root, 'src/page/plot.css'), 'utf8')
const plScript = (await build({ ...common, entryPoints: [join(root, 'src/page/plot.ts')], format: 'iife', target: 'es2020' })).outputFiles[0].text
if (/<\/script/i.test(plScript)) throw new Error('The stage script contains "</script": it would end the page early.')
const plHtml = readFileSync(join(root, 'src/page/template.html'), 'utf8').replace(/\{\{(VERSION|CSS|JS)\}\}/g, (_, k) => ({ VERSION: `${release}, engine ${version}`, CSS: plCss, JS: plScript })[k])
writeFileSync(join(skill, 'assets/plot.html'), plHtml)
// the lesson page — visual-explainer's player, from its npm package
copyFileSync(join(repo, 'node_modules/@ruinosus/visual-explainer/assets/player.html'), join(skill, 'assets/lesson.html'))
// the kit's headless browser (the lesson's reviewer, the map's check) and page helpers
vendor(join(skill, 'scripts'), ['browser.mjs', 'page.mjs'])
// the workbook reader is way-of-working' own (Node only)
copyFileSync(join(repo, 'skills/way-of-working/scripts/read-xlsx.mjs'), join(skill, 'scripts/read-xlsx.mjs'))
// references/keys.md, from the names the engine uses
const { keysMarkdown } = await import(`data:text/javascript;base64,${Buffer.from((await build({ ...common, entryPoints: [join(root, 'src/labels.ts')], format: 'esm', platform: 'node' })).outputFiles[0].text).toString('base64')}`)
mkdirSync(join(skill, 'references'), { recursive: true })
writeFileSync(join(skill, 'references/keys.md'), keysMarkdown())
// references/playbill.md, from the words the RH uses
const { playbillMarkdown } = await import(`data:text/javascript;base64,${Buffer.from((await build({ ...common, entryPoints: [join(root, 'src/playbillDoc.ts')], format: 'esm', platform: 'node' })).outputFiles[0].text).toString('base64')}`)
writeFileSync(join(skill, 'references/playbill.md'), playbillMarkdown())
writeFileSync(join(skill, 'assets/VERSION'), `engine ${version}\nvisual-explainer ${chalk}\n`)
console.log(`✓ assets from the engine ${version} and visual-explainer ${chalk}: engine.mjs ${(engine.outputFiles[0].text.length / 1024).toFixed(0)} KB, map.html ${(html.length / 1024).toFixed(0)} KB, playbill.html ${(pbHtml.length / 1024).toFixed(0)} KB, plot.html ${(plHtml.length / 1024).toFixed(0)} KB, read-xlsx.mjs, references/keys.md and playbill.md`)
