// Builds the generated parts of the skill from the way engine's source, so there is one engine: the rules for Node
// (scripts/engine.mjs: read, check, review, the workbook there and back, the lesson), the map page with its code inside
// (assets/map.html), the lesson page (assets/lesson.html, chalk-talk's player) and assets/VERSION. Where the sources are
// is in tools/sources.json (kept out of git; see sources.example.json). Run: npm run assets. Never edit the generated
// files by hand.
import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'
import { copyFileSync, existsSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { vendor } from 'chalk-talk/kit/tools/vendor.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '../../..') // the house-lights repository
const skill = resolve(here, '../../../skills/gates-and-handoffs')
const config = join(here, 'sources.json')
if (!existsSync(config)) {
  console.error('✗ tools/sources.json is missing: copy sources.example.json and point it at the way engine and chalk-talk.')
  process.exit(1)
}
const sources = JSON.parse(readFileSync(config, 'utf8'))
const engine = resolve(here, sources.engine)
// chalk-talk (its player page and the skills kit) comes from its npm package, in tools/node_modules.
const chalkTalk = join(repo, 'node_modules/chalk-talk')

// A source must be committed, so VERSION says exactly what the skill was built from.
function pinned(dir, paths) {
  if (execFileSync('git', ['-C', dir, 'status', '--porcelain', '--', ...paths], { encoding: 'utf8' }).trim()) {
    throw new Error(`${dir} has uncommitted changes in ${paths.join(', ')}: commit them first.`)
  }
  return execFileSync('git', ['-C', dir, 'describe', '--tags', '--always'], { encoding: 'utf8' }).trim()
}
const version = pinned(engine, ['ways', 'murals', 'drawing'])
const playerVersion = JSON.parse(readFileSync(join(chalkTalk, 'package.json'), 'utf8')).version
const banner = `// GENERATED by tools/assets.mjs from the way engine ${version}. Do not edit.`

// tools/.engine points at the engine, for the typecheck (tsconfig.json).
rmSync(join(here, '.engine'), { force: true })
symlinkSync(engine, join(here, '.engine'))

// The engine's own files have no side effects: what the skill does not use (the platform's screens, i18n, React) is
// left out of the bundles.
const pure = {
  name: 'pure',
  setup(b) {
    b.onResolve({ filter: /^\.\.?\// }, async (a) => {
      if (a.pluginData === 'resolving') return undefined
      const r = await b.resolve(a.path, { resolveDir: a.resolveDir, kind: a.kind, pluginData: 'resolving' })
      return r.errors.length || r.path.includes('node_modules') || !r.path.startsWith(engine) ? r : { ...r, sideEffects: false }
    })
  },
}

// The rules, for scripts/build.mjs: one minified ES module with what they use (yaml, zod) inside.
const rules = await build({
  stdin: {
    contents: [
      "export { readWay, exportWay, STAGE_DOOR } from './ways/portable'",
      "export { checkWay, problemText, wayDiff, applyRows, show, itemName } from './ways/wayChanges'",
      "export { reviewWay } from './ways/review'",
      "export { workbookOf } from './ways/workbook'",
      "export { xlsx } from './ways/xlsx'",
      "export { fromSheets, sheetKeyOf } from './ways/fromSheets'",
      "export { wayLesson } from './ways/lesson'",
      "export { validateScene } from './drawing/recipe'",
    ].join('\n'),
    resolveDir: engine,
    loader: 'ts',
  },
  bundle: true, format: 'esm', platform: 'node', target: 'node18', minify: true, write: false, logLevel: 'warning',
  nodePaths: [join(engine, 'node_modules')],
  plugins: [pure],
  banner: { js: "import { createRequire } from 'node:module'; const require = createRequire(import.meta.url);" },
})
const code = rules.outputFiles[0].text
writeFileSync(join(skill, 'scripts/engine.mjs'), `${banner}\n${code}`)

// The map: the page and its code in one file, the way to draw in its {{WAY}} slot.
const css = readFileSync(join(here, 'map/map.css'), 'utf8')
const map = await build({
  entryPoints: [join(here, 'map/map.ts')],
  bundle: true, format: 'iife', target: 'es2020', minify: true, write: false, logLevel: 'warning',
  alias: { '@engine': engine },
  nodePaths: [join(engine, 'node_modules')],
  plugins: [pure],
  define: { __MAP_CSS__: JSON.stringify(css) },
})
const script = map.outputFiles[0].text
if (/<\/script/i.test(script)) throw new Error('The map script contains "</script": it would end the page early.')
const fill = { VERSION: version, CSS: css, JS: script }
const page = readFileSync(join(here, 'map/template.html'), 'utf8').replace(/\{\{(VERSION|CSS|JS)\}\}/g, (_, k) => fill[k])
if (!page.includes('{{WAY}}')) throw new Error('The template lost its {{WAY}} slot.')
writeFileSync(join(skill, 'assets/map.html'), page)

// The lesson: chalk-talk's player page (its {{RECIPE}} slot); the kit's headless browser (it runs the lesson's
// reviewer) and page helpers, copied into the skill.
copyFileSync(join(chalkTalk, 'assets/player.html'), join(skill, 'assets/lesson.html'))
vendor(join(skill, 'scripts'), ['browser.mjs', 'page.mjs'])

writeFileSync(join(skill, 'assets/VERSION'), `engine ${version}\nchalk-talk ${playerVersion}\n`)
console.log(`✓ assets from the engine ${version} and chalk-talk ${playerVersion}: engine.mjs ${(code.length / 1024).toFixed(0)} KB, map.html ${(page.length / 1024).toFixed(0)} KB`)
