// Builds workday-integration's CLI as one file a skill can carry (claude.ai installs no packages): src/ and the XML
// parser (saxes, ISC) bundled by esbuild into plugins/workday-integration/skills/workday-integration/scripts/wws.mjs.
import { build } from 'esbuild'
import { mkdirSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const plugin = join(here, '../../../plugins/workday-integration')
const version = JSON.parse(readFileSync(join(plugin, '.claude-plugin/plugin.json'), 'utf8')).version
const out = join(plugin, 'skills/workday-integration/scripts/wws.mjs')
mkdirSync(dirname(out), { recursive: true })
await build({
  entryPoints: [join(here, '../src/main.mjs')], bundle: true, format: 'esm', platform: 'node', target: 'node18',
  outfile: out, legalComments: 'inline', logLevel: 'warning',
  banner: { js: `#!/usr/bin/env node\n// GENERATED by dev/workday-integration/tools/assets.mjs (workday-integration ${version}) from dev/workday-integration/src and saxes (ISC). Do not edit.` },
})
// the MCP server: the same core, with the MCP TypeScript SDK (MIT) and zod (MIT) inside
await build({
  stdin: { contents: "import { main } from './mcp.mjs'\nawait main()\n", resolveDir: join(here, '../src'), loader: 'js' },
  bundle: true, format: 'esm', platform: 'node', target: 'node18', outfile: join(dirname(out), 'mcp.mjs'),
  legalComments: 'inline', logLevel: 'warning', define: { __WWS_VERSION__: JSON.stringify(version) },
  // a CommonJS dependency inside an ES module needs require
  banner: { js: `#!/usr/bin/env node\n// GENERATED by dev/workday-integration/tools/assets.mjs (workday-integration ${version}) from dev/workday-integration/src, saxes (ISC), @modelcontextprotocol/sdk and zod (MIT). Do not edit.\nimport { createRequire as __wwsRequire } from 'node:module'; const require = __wwsRequire(import.meta.url);` },
})
console.log(`✓ assets of workday-integration ${version}: scripts/wws.mjs, scripts/mcp.mjs`)
